func TestPickGatewayIP(t *testing.T) {
	cases := []struct {
		subnet, explicit, want string
		wantErr                bool
	}{
		{"10.213.0.0/16", "", "10.213.0.2", false},
		{"10.50.0.0/16", "", "10.50.0.2", false}, // reused network with a different subnet
		{"10.213.0.0/16", "10.213.9.9", "10.213.9.9", false},
		{"10.213.0.0/16", "10.214.0.2", "", true},
		{"bogus", "", "", true},
	}
	for _, c := range cases {
		got, err := pickGatewayIP(c.subnet, c.explicit)
		if (err != nil) != c.wantErr || got != c.want {
			t.Errorf("pickGatewayIP(%q,%q) = %q,%v; want %q, err=%v", c.subnet, c.explicit, got, err, c.want, c.wantErr)
		}
	}
}

func TestDynamicIPRangeExcludesGateway(t *testing.T) {
	cases := map[[2]string]string{
		{"10.213.0.0/16", "10.213.0.2"}:       "10.213.128.0/17",
		{"10.213.0.0/16", "10.213.200.2"}:     "10.213.0.0/17",
		{"172.30.8.0/24", "172.30.8.2"}:       "172.30.8.128/25",
		{"192.168.100.0/22", "192.168.100.2"}: "192.168.102.0/23",
	}
	for in, want := range cases {
		got, err := dynamicIPRange(in[0], in[1])
		if err != nil || got != want {
			t.Errorf("dynamicIPRange(%v) = %q,%v; want %q", in, got, err, want)
		}
	}
}

const dockerUserNetResolv = `# Generated by Docker Engine.
nameserver 127.0.0.11
options ndots:0

# Based on host file: '/etc/resolv.conf' (internal resolver)
# ExtServers: [host(127.0.0.53) 100.100.2.136 host(192.168.65.7)]
# Overrides: []
`

func TestResolvConfUpstreamsAndFallback(t *testing.T) {
	rc := parseResolvConf(strings.NewReader(dockerUserNetResolv))
	// The gateway shares the agent's netns, so 127.0.0.11 is a valid upstream.
	if got, want := rc.upstreams(), []string{"127.0.0.11:53"}; !reflect.DeepEqual(got, want) {
		t.Errorf("upstreams = %v, want %v", got, want)
	}
	// Project containers can't reach loopback resolvers of other namespaces.
	if got, want := rc.fallbackDNS(), []string{"100.100.2.136", "192.168.65.7"}; !reflect.DeepEqual(got, want) {
		t.Errorf("fallbackDNS = %v, want %v", got, want)
	}

	legacy := parseResolvConf(strings.NewReader("nameserver 8.8.8.8\nnameserver 8.8.8.8\nnameserver 1.1.1.1\n"))
	if got, want := legacy.fallbackDNS(), []string{"8.8.8.8", "1.1.1.1"}; !reflect.DeepEqual(got, want) {
		t.Errorf("legacy fallbackDNS = %v, want %v", got, want)
	}
}

func TestContainerIDFromMountinfo(t *testing.T) {
	id := strings.Repeat("ab12", 16)
	mi := "100 90 0:50 / / rw - overlay overlay rw\n" +
		"200 100 254:1 /docker/containers/" + id + "/resolv.conf /etc/resolv.conf rw - ext4 /dev/vda1 rw\n" +
		"201 100 254:1 /docker/containers/" + id + "/hostname /etc/hostname rw - ext4 /dev/vda1 rw\n"
	if got := containerIDFromMountinfo(bufio.NewScanner(strings.NewReader(mi))); got != id {
		t.Fatalf("got %q, want %q", got, id)
	}
	native := "100 90 0:50 / / rw - ext4 /dev/sda1 rw\n"
	if got := containerIDFromMountinfo(bufio.NewScanner(strings.NewReader(native))); got != "" {
		t.Fatalf("native host should yield no container id, got %q", got)
	}
}

